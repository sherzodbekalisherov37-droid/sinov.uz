// Helper to ensure monthly tests and beginner easy tests are in current tests state
export const syncMonthlyAndBeginnerTests = (existingTests: MockTest[]): MockTest[] => {
  const existingIds = new Set(existingTests.map((t) => t.id));
  const toAdd: MockTest[] = [];

  // Add beginner easy tests if not exist
  BEGINNER_EASY_TESTS.forEach((t) => {
    if (!existingIds.has(t.id)) {
      toAdd.push(t);
      existingIds.add(t.id);
    }
  });

  // Add monthly refreshed mock tests if not exist
  MONTHLY_REFRESH_TESTS.forEach((t) => {
    if (!existingIds.has(t.id)) {
      toAdd.push(t);
      existingIds.add(t.id);
    }
  });

  return [...toAdd, ...existingTests];
};
